/**
 * Generates global.css from src/theme/tokens.ts.
 *
 * tokens.ts is the single source of truth. This script emits the CSS custom
 * properties that the Tailwind/NativeWind theme references, for both themes,
 * so no colour value is ever typed twice. Run `npm run theme:gen` after
 * editing tokens.
 */
const { writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

const root = resolve(__dirname, '..');
const jiti = require('jiti')(__filename, { interopDefault: true, esmResolve: true });

const { lightColors, darkColors } = jiti(resolve(root, 'src/theme/tokens.ts'));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** colors.brand.default -> --color-brand ; colors.text.strong -> --color-text-strong */
function flatten(colors) {
  const out = [];
  for (const [group, value] of Object.entries(colors)) {
    if (group === 'avatar') {
      value.forEach((pair, i) => {
        out.push([`--color-avatar-${i}-bg`, pair.bg]);
        out.push([`--color-avatar-${i}-fg`, pair.fg]);
      });
      continue;
    }
    for (const [key, hex] of Object.entries(value)) {
      const name =
        key === 'default'
          ? `--color-${kebab(group)}`
          : `--color-${kebab(group)}-${kebab(key)}`;
      out.push([name, hex]);
    }
  }
  return out;
}

const block = (entries) => entries.map(([k, v]) => `  ${k}: ${v};`).join('\n');

const light = flatten(lightColors);
const dark = flatten(darkColors);

const css = `/* GENERATED by scripts/gen-theme-css.cjs — do not edit.
   Source of truth: src/theme/tokens.ts. Run \`npm run theme:gen\`. */

@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
${block(light)}
}

.dark {
${block(dark)}
}
`;

writeFileSync(resolve(root, 'global.css'), css, 'utf8');
console.log(`global.css written — ${light.length} variables per theme`);
